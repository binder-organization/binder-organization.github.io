function getPref(key, fallback) {
  try {
    var v = localStorage.getItem(key);
    if (v !== null && v !== undefined && v !== "") return v;
  } catch (e) {}
  var c = document.cookie.match(new RegExp("(^| )" + key + "=([^;]+)"));
  if (c) return decodeURIComponent(c[2]);
  return fallback;
}

function setPref(key, val) {
  try {
    localStorage.setItem(key, val);
  } catch (e) {}
  var date = new Date();
  date.setTime(date.getTime() + 365 * 24 * 60 * 60 * 1000);
  document.cookie =
    key +
    "=" +
    encodeURIComponent(val) +
    ";expires=" +
    date.toUTCString() +
    ";path=/;SameSite=Lax";
}

function setLanguage(lang) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  setPref("lang", lang);

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var key = el.getAttribute("data-i18n");
    if (i18n[lang] && i18n[lang][key]) {
      if (el.tagName === "TITLE") {
        document.title = i18n[lang][key];
      } else if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = i18n[lang][key];
      } else {
        el.textContent = i18n[lang][key];
      }
    }
  });

  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  // 由脚本渲染出来的内容（文章列表与正文）不在 data-i18n 体系内，
  // 靠这个事件通知它们按新语言重绘。
  document.dispatchEvent(new CustomEvent("binder:language-change", { detail: { lang: lang } }));
}

function initI18n() {
  var savedLang = getPref("lang", "zh");
  setLanguage(savedLang);

  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    btn.addEventListener("click", function () {
      setLanguage(btn.getAttribute("data-lang"));
    });
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initI18n);
} else {
  initI18n();
}
